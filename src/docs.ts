import { rawAllowed } from "./api-get.js";
import { catalogue, help, inventory, listPaging } from "./catalogue.js";

const COMPOSITE_DEPLOYMENTS: Readonly<Record<string, readonly string[]>> = {
  home: ["QUX", "RUX"],
  doctor: ["QUX", "RUX"],
  "api get": ["QUX", "RUX"],
};

function compositeDocumentLines(leaf: string): string[] | undefined {
  if (leaf === "home") {
    return ["Network command when configured; reads one bounded active-detection page through the selected QUX v2.5 or RUX v3.4 profile."];
  }
  if (leaf === "doctor") {
    const qux = inventory.operations.find((operation) => operation.id === "qux.detection.list");
    const quxLabel = qux ? `${qux.deployment.toUpperCase()} API ${qux.apiVersion}` : "QUX API";
    return [
      `- \`qux.detection.list\`: ${quxLabel} bounded detection read per QUX profile`,
      "- `rux.oauth.exchange`: RUX OAuth exchange per RUX profile (no resource read)",
    ];
  }
  if (leaf === "api get") {
    return ["Network command; reads one allowlisted QUX or RUX GET operation through the configured profile."];
  }
  return undefined;
}

export function commandSummary(): string {
  return [
    "| Domain | Commands | Deployment |",
    "| --- | --- | --- |",
    ...[...new Set(Object.keys(catalogue).map((leaf) => leaf.split(" ")[0]!))].map((domain) => {
      const leaves = Object.keys(catalogue).filter((leaf) => leaf.split(" ")[0] === domain);
      const deployments = [...new Set([...inventory.operations.filter((operation) =>
        operation.disposition === "named" && operation.command && leaves.includes(operation.command))
        .map((operation) => operation.deployment.toUpperCase()),
        ...leaves.flatMap((leaf) => COMPOSITE_DEPLOYMENTS[leaf] ?? [])])].sort();
      return `| \`${domain}\` | ${leaves.map((leaf) => `\`${leaf}\``).join(", ")} | ${deployments.join(", ") || "Local"} |`;
    }),
  ].join("\n");
}

function inventoryLeaf(leaf: string): string {
  if (leaf === "group member add" || leaf === "group member remove") return "group member set";
  return leaf;
}

export function commandDocument(): string {
  return [
    "<!-- Generated by scripts/generate-docs.mjs from the executable catalogue. Do not hand-edit. -->",
    "",
    "# Command reference",
    "",
    "[Domain summary](#domain-summary) · [Command table](#command-table) · [Command details](#command-details)",
    "",
    "Run `vectra-axi <command> --help` for flags and examples. Deployment support below is operation-specific.",
    "",
    "## Domain summary",
    "",
    commandSummary(),
    "",
    "## Command table",
    "",
    skillCommandTable(),
    "",
    "## Command details",
    "",
    ...Object.keys(catalogue).map((leaf) => `- [${leaf}](#${leaf.replaceAll(" ", "-")})`),
    "",
    ...Object.entries(catalogue).flatMap(([leaf, command]) => {
      const operations = inventory.operations.filter((operation) => operation.command === inventoryLeaf(leaf) && operation.disposition === "named");
      return [
        `## ${leaf}`,
        "",
        command.description,
        "",
        ...(operations.length ? operations.map((operation) => `- \`${operation.id}\`: ${operation.deployment.toUpperCase()} API ${operation.apiVersion}`) : (compositeDocumentLines(leaf) ?? ["Local command; no Vectra API request."])),
        "",
        ...(listPaging(leaf) ? [listPaging(leaf)!, ""] : []),
        "```json",
        JSON.stringify(help(leaf), null, 2),
        "```",
        "",
      ];
    }),
  ].join("\n");
}

// PACK-01: single source for generated release records. The committed
// skills/vectra-axi/SKILL.md command table, docs/coverage.md,
// docs/commands.md are
// projections of the executable catalogue and the capability inventory, so
// help, skill, coverage and the command reference cannot drift apart.
// scripts/generate-docs.mjs writes those files; test/generated.test.ts
// and docs:check fail when they are stale.

// One row per executable leaf in catalogue order, matching the home-view
// help. Every leaf is implemented by a vectra-axi handler (native).
// Local views stay offline; QUX and RUX reads use the read-only session, tag
// replaces, bulk tag changes, note appends, note edits/deletes, assignment
// sets and assignment resolves use the gated WRITE-00 coordinator.
export function skillCommandTable(): string {
  return [
    "| Command | Capability | Vectra effect | List pagination |",
    "|---|---|---|---|",
    ...Object.keys(catalogue).map((leaf) => {
      const effects = inventory.operations
        .filter((operation) => operation.command === inventoryLeaf(leaf)).map((operation) => operation.effect);
      const rank = (effect: string): number => effect === "disruptive" ? 3 : effect === "write" ? 2 : effect === "read" ? 1 : 2;
      const effect = effects.sort((a, b) => rank(b) - rank(a))[0] ?? "read";
      return `| \`npx -y @knowttl/vectra-axi ${leaf}\` | native | ${effect} | ${listPaging(leaf) ?? "-"} |`;
    }),
  ].join("\n");
}

const DISPOSITIONS = ["named", "implemented", "reviewed-raw", "planned", "blocked", "unavailable", "deprecated", "unreviewed"] as const;

export function coverageDocument(): string {
  const operations = inventory.operations;
  const count = (disposition: string): number =>
    operations.filter((operation) => operation.disposition === disposition).length;
  // The Raw column records each route's raw disposition: `raw` where the
  // `api get` leaf serves the operation under its recorded query/field
  // policy, otherwise the operation's own disposition. Raw-eligible
  // operations keep their `named` disposition and their named leaves.
  const rows = operations.map((operation) =>
    `| \`${operation.id}\` | ${operation.command ?? "-"} | ${operation.slice} | ${operation.deployment} ${operation.apiVersion} | ${operation.paging} | ${operation.disposition} | ${rawAllowed(operation) ? "raw" : operation.disposition} |`);
  const families = inventory.deferredFamilies.map((family) =>
    `- \`${family.id}\` (${family.deployment} ${family.apiVersion}, ${family.disposition}): ${family.rationale}`);
  return [
    "<!-- Generated by scripts/generate-docs.mjs from inventory/capabilities.json. Do not hand-edit. -->",
    "",
    "# vectra-axi coverage",
    "",
    "[Counts](#counts) · [Operations](#operations) · [Deferred families](#deferred-families)",
    "",
    "This is the supported QUX and RUX SOC read surface with gated QUX/RUX single and bulk tag-write, note-append, RUX bulk note-append, assignment-write/resolve, note edit/delete, detection close/open, detection fixed set, detection triage set/clear, group create/edit/delete, group member add/remove/set, host key-asset, assignment outcome create/edit/delete, triage rule create/edit/delete, proxy create/edit/(RUX) delete, threat-feed create/edit/delete and file set/delete, internal-network set, syslog/kafka export set, RUX notification destination create/edit/delete, Match enablement set, ruleset upload/delete and assignment set/delete, and host/account close families, not full Vectra API coverage.",
    "Only `named` operations have an implemented, tested command leaf.",
    "The `implemented` disposition records tested internal OAuth exchanges with no command leaf;",
    "other operations remain planned, blocked or unreviewed until their own slices ship.",
    "The reviewed `api get` raw-read leaf serves the allowlisted GET operations marked `raw` below;",
    "there is no unrestricted passthrough.",
    "",
    "## Counts",
    "",
    ...DISPOSITIONS.map((disposition) => `- ${disposition}: ${count(disposition)}`),
    "",
    "## Operations",
    "",
    "| Operation | Command | Slice | Deployment/API | Paging | Disposition | Raw |",
    "|---|---|---|---|---|---|---|",
    ...rows,
    "",
    "## Deferred families",
    "",
    ...families,
    "",
  ].join("\n");
}
